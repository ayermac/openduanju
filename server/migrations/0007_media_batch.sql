-- MEDIA-002: persistent media batches, episode items, verified assets and
-- the review task that a fully ready batch creates.
CREATE TABLE IF NOT EXISTS media_batch (
  id BIGINT NOT NULL AUTO_INCREMENT,
  series_id BIGINT NOT NULL,
  revision_id BIGINT NOT NULL,
  selection_hash VARCHAR(64) NOT NULL DEFAULT '',
  profile_version VARCHAR(64) NOT NULL DEFAULT '',
  input_kind VARCHAR(16) NOT NULL DEFAULT 'sdk',
  status VARCHAR(16) NOT NULL DEFAULT 'queued',
  cover_status VARCHAR(16) NOT NULL DEFAULT 'pending',
  item_total INT NOT NULL DEFAULT 0,
  item_ready INT NOT NULL DEFAULT 0,
  item_failed INT NOT NULL DEFAULT 0,
  cancel_requested TINYINT(1) NOT NULL DEFAULT 0,
  lease_owner VARCHAR(64) NOT NULL DEFAULT '',
  lease_until DATETIME(6) NULL,
  version INT NOT NULL DEFAULT 1,
  error_code VARCHAR(64) NOT NULL DEFAULT '',
  error_message VARCHAR(512) NOT NULL DEFAULT '',
  created_by VARCHAR(64) NOT NULL DEFAULT '',
  review_task_id BIGINT NOT NULL DEFAULT 0,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uk_media_batch_revision (revision_id),
  KEY idx_media_batch_series (series_id),
  KEY idx_media_batch_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS media_item (
  id BIGINT NOT NULL AUTO_INCREMENT,
  batch_id BIGINT NOT NULL,
  episode_id BIGINT NOT NULL,
  external_id VARCHAR(64) NOT NULL DEFAULT '',
  episode_no INT NOT NULL DEFAULT 0,
  status VARCHAR(16) NOT NULL DEFAULT 'queued',
  attempt INT NOT NULL DEFAULT 0,
  retryable TINYINT(1) NOT NULL DEFAULT 0,
  next_eligible_at DATETIME(6) NULL,
  error_code VARCHAR(64) NOT NULL DEFAULT '',
  error_message VARCHAR(512) NOT NULL DEFAULT '',
  lease_generation INT NOT NULL DEFAULT 0,
  lease_owner VARCHAR(64) NOT NULL DEFAULT '',
  lease_until DATETIME(6) NULL,
  input_version INT NOT NULL DEFAULT 0,
  asset_id BIGINT NOT NULL DEFAULT 0,
  object_provider VARCHAR(16) NOT NULL DEFAULT '',
  object_bucket VARCHAR(128) NOT NULL DEFAULT '',
  object_region VARCHAR(64) NOT NULL DEFAULT '',
  object_key VARCHAR(512) NOT NULL DEFAULT '',
  object_version VARCHAR(128) NOT NULL DEFAULT '',
  sha256 VARCHAR(64) NOT NULL DEFAULT '',
  size_bytes BIGINT NOT NULL DEFAULT 0,
  content_type VARCHAR(64) NOT NULL DEFAULT '',
  codec VARCHAR(32) NOT NULL DEFAULT '',
  duration_ms BIGINT NOT NULL DEFAULT 0,
  width INT NOT NULL DEFAULT 0,
  height INT NOT NULL DEFAULT 0,
  version INT NOT NULL DEFAULT 1,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uk_media_item_episode (batch_id, episode_id),
  KEY idx_media_item_status (status, next_eligible_at),
  KEY idx_media_item_lease (lease_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS media_asset (
  id BIGINT NOT NULL AUTO_INCREMENT,
  provider VARCHAR(16) NOT NULL DEFAULT '',
  bucket VARCHAR(128) NOT NULL DEFAULT '',
  region VARCHAR(64) NOT NULL DEFAULT '',
  object_key VARCHAR(512) NOT NULL DEFAULT '',
  object_version VARCHAR(128) NOT NULL DEFAULT '',
  sha256 VARCHAR(64) NOT NULL DEFAULT '',
  size_bytes BIGINT NOT NULL DEFAULT 0,
  content_type VARCHAR(64) NOT NULL DEFAULT '',
  codec VARCHAR(32) NOT NULL DEFAULT '',
  duration_ms BIGINT NOT NULL DEFAULT 0,
  width INT NOT NULL DEFAULT 0,
  height INT NOT NULL DEFAULT 0,
  state VARCHAR(16) NOT NULL DEFAULT 'verified',
  revision_id BIGINT NOT NULL DEFAULT 0,
  episode_id BIGINT NOT NULL DEFAULT 0,
  batch_id BIGINT NOT NULL DEFAULT 0,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uk_media_asset_object (provider, bucket, region, object_key(255), object_version),
  KEY idx_media_asset_revision (revision_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS review_task (
  id BIGINT NOT NULL AUTO_INCREMENT,
  revision_id BIGINT NOT NULL,
  series_id BIGINT NOT NULL,
  batch_id BIGINT NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'open',
  assignee VARCHAR(64) NOT NULL DEFAULT '',
  submitted_by VARCHAR(64) NOT NULL DEFAULT '',
  version INT NOT NULL DEFAULT 1,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uk_review_task_revision (revision_id),
  KEY idx_review_task_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
